# ============================================
# پیام‌های مناسبتی (اختیاری - بر اساس تاریخ میلادی)
# اگه مناسبت خاصی هست، پیام مخصوص خودش رو بفرست
# ============================================
SPECIAL_MESSAGES = {
    # (ماه، روز): "پیام مناسبتی"
    # مثال: (2, 14): "ولنتاین مبارک مائده! 🌹",
}

def get_message():
    """انتخاب پیام مناسب - اگه مناسبت خاصی بود اون رو، وگرنه یه پیام تصادفی"""
    today = datetime.utcnow()
    key = (today.month, today.day)
    
    if key in SPECIAL_MESSAGES:
        return SPECIAL_MESSAGES[key]
    
    return random.choice(MORNING_MESSAGES)

def send_message():
    message = get_message()
    url = f"https://api.telegram.org/bot{TOKEN}/sendMessage"
    payload = {"chat_id": CHAT_ID, "text": message}
    
    response = requests.post(url, data=payload)
    
    if response.status_code == 200:
        print(f"✅ پیام ارسال شد: {message}")
    else:
        print(f"❌ خطا: {response.text}")

if __name__ == "__main__":
    send_message()
